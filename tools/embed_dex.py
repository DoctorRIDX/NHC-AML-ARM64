#!/usr/bin/env python3
"""Turn a classes.dex into a C++ header (generated/nhc_ui_dex.h) that the plugin embeds."""
import pathlib
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: embed_dex.py <classes.dex> <output.h>", file=sys.stderr)
        return 2
    data = pathlib.Path(sys.argv[1]).read_bytes()
    if data[:4] != b"dex\n":
        print("error: input is not a DEX file", file=sys.stderr)
        return 1
    rows = []
    for i in range(0, len(data), 12):
        rows.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    header = (
        "// Generated by tools/embed_dex.py - do not edit.\n"
        "#pragma once\n"
        "#include <cstddef>\n"
        "alignas(8) static const unsigned char nhc_ui_dex[] = {\n"
        + "\n".join(rows)
        + "\n};\n"
        "static const size_t nhc_ui_dex_len = %d;\n" % len(data)
    )
    pathlib.Path(sys.argv[2]).write_text(header)
    print("wrote %s (%d bytes of DEX)" % (sys.argv[2], len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
